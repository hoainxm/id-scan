/** "Tỉnh Nam Định" -> "Công an tỉnh Nam Định"; "Thành phố Hà Nội" -> "Công an thành phố Hà Nội". */
export function buildIssuers(oldProvinceNames = []) {
  const police = oldProvinceNames.map((name) => {
    const local = String(name).trim();
    const value = `Công an ${local.charAt(0).toLowerCase()}${local.slice(1)}`;
    const bare = local.replace(/^(Tỉnh|Thành phố)\s+/u, "");
    return { value, aliases: [`CA ${bare}`, `Công an ${bare}`] };
  });

  return [...BASE_ISSUERS, ...police];
}
